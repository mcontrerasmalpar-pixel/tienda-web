-- Un solo RPC = una transacción. Cualquier error revierte productos y taxonomía.
create or replace function public.import_catalog(rows jsonb, mode text default 'insert') returns integer
language plpgsql security invoker set search_path = '' as $$
declare item jsonb; n integer := 0; cat bigint; sub bigint; code text; price numeric; result integer;
begin
  if not public.is_catalog_admin() then raise exception 'Se requiere un administrador del catálogo' using errcode = '42501'; end if;
  if mode is null or mode not in ('insert','upsert') then raise exception 'Modo inválido'; end if;
  if rows is null or jsonb_typeof(rows) <> 'array' then raise exception 'Se esperaba una lista'; end if;
  if jsonb_array_length(rows) not between 1 and 1000 then raise exception 'Se permiten 1 a 1000 productos'; end if;
  if exists (select 1 from jsonb_array_elements(rows) e group by upper(btrim(e->>'codigo')) having count(*) > 1) then raise exception 'Códigos repetidos en el archivo'; end if;
  for item in select value from jsonb_array_elements(rows) loop
    n := n + 1;
    begin
      code := upper(btrim(item->>'codigo'));
      if code is null or code !~ '^[A-Z0-9][A-Z0-9._/-]{0,63}$' then raise exception 'Código inválido'; end if;
      if coalesce(length(btrim(item->>'nombre')),0) not between 1 and 200 then raise exception 'Nombre inválido'; end if;
      if coalesce(length(btrim(item->>'categoria')),0) not between 1 and 100 or coalesce(length(btrim(item->>'subcategoria')),0) > 100 then raise exception 'Categoría/subcategoría inválida'; end if;
      if coalesce(item->>'precio','') !~ '^[0-9]+(\.[0-9]{1,2})?$' then raise exception 'Precio inválido'; end if;
      price := (item->>'precio')::numeric;
      if price > 99999999.99 then raise exception 'Precio fuera de rango'; end if;
      if jsonb_typeof(item->'activo') is distinct from 'boolean' or jsonb_typeof(item->'destacado') is distinct from 'boolean' then raise exception 'activo y destacado deben ser booleanos'; end if;
      if coalesce(length(item->>'descripcion'),0) > 5000 or coalesce(length(item->>'imagen_url'),0) > 2048 then raise exception 'Texto demasiado largo'; end if;
      if (item->>'imagen_url' ~* '^[a-z][a-z0-9+.-]*:' and item->>'imagen_url' !~* '^https?://') or item->>'imagen_url' like '//%' then raise exception 'URL de imagen inválida'; end if;
      insert into public.categories(nombre) values (btrim(item->>'categoria')) on conflict do nothing;
      select id into cat from public.categories where lower(btrim(nombre)) = lower(btrim(item->>'categoria'));
      sub := null;
      if nullif(btrim(item->>'subcategoria'), '') is not null then
        insert into public.subcategories(category_id,nombre) values (cat,btrim(item->>'subcategoria')) on conflict do nothing;
        select id into sub from public.subcategories where category_id = cat and lower(btrim(nombre)) = lower(btrim(item->>'subcategoria'));
      end if;
      if mode = 'upsert' then
        insert into public.products(codigo,nombre,category_id,subcategory_id,precio,descripcion,imagen_url,activo,destacado)
        values(code,btrim(item->>'nombre'),cat,sub,price,item->>'descripcion',item->>'imagen_url',(item->>'activo')::boolean,(item->>'destacado')::boolean)
        on conflict (codigo) do update set nombre=excluded.nombre, category_id=excluded.category_id, subcategory_id=excluded.subcategory_id, categoria=excluded.categoria, precio=excluded.precio, descripcion=excluded.descripcion, imagen_url=excluded.imagen_url, activo=excluded.activo, destacado=excluded.destacado;
      else
        insert into public.products(codigo,nombre,category_id,subcategory_id,precio,descripcion,imagen_url,activo,destacado)
        values(code,btrim(item->>'nombre'),cat,sub,price,item->>'descripcion',item->>'imagen_url',(item->>'activo')::boolean,(item->>'destacado')::boolean);
      end if;
    exception when others then raise exception 'Registro % (código %): %', n + 1, coalesce(code,'?'), sqlerrm; end;
  end loop;
  result := n; return result;
end $$;
revoke all on function public.import_catalog(jsonb,text) from public, anon;
grant execute on function public.import_catalog(jsonb,text) to authenticated;
notify pgrst, 'reload schema';
commit;
