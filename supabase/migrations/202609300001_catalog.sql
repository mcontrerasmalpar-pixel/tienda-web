grant execute on function public.is_catalog_admin() to anon, authenticated;

-- Trigger de compatibilidad para el campo categoria antiguo y códigos canónicos.
create or replace function public.sync_catalog_product() returns trigger
language plpgsql security invoker set search_path = '' as $$
declare resolved bigint;
begin
  new.codigo := upper(btrim(new.codigo));
  if new.category_id is null or (tg_op = 'UPDATE' and new.categoria is distinct from old.categoria and new.category_id is not distinct from old.category_id) then
    if nullif(btrim(new.categoria), '') is null then raise exception 'Categoría obligatoria'; end if;
    insert into public.categories(nombre) values (btrim(new.categoria)) on conflict do nothing;
    select id into resolved from public.categories where lower(btrim(nombre)) = lower(btrim(new.categoria));
    new.category_id := resolved;
  end if;
  select nombre into new.categoria from public.categories where id = new.category_id;
  if new.categoria is null then raise exception 'Categoría no encontrada'; end if;
  new.updated_at := now();
  return new;
end $$;
revoke all on function public.sync_catalog_product() from public, anon, authenticated;
drop trigger if exists sync_catalog_product on public.products;
create trigger sync_catalog_product before insert or update on public.products for each row execute function public.sync_catalog_product();

-- Reemplazar las políticas anteriores (permisivas) de estas tablas de catálogo.
do $$ declare r record; t text;
begin
  for r in select schemaname, tablename, policyname from pg_policies where schemaname = 'public' and tablename in ('products','categories','subcategories') loop
    execute format('drop policy %I on %I.%I', r.policyname, r.schemaname, r.tablename);
  end loop;
  foreach t in array array['products','categories','subcategories'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from public, anon, authenticated', t);
    execute format('grant select on public.%I to anon, authenticated', t);
    execute format('grant insert, update, delete on public.%I to authenticated', t);
    execute format('create policy catalog_admin_write on public.%I for all to authenticated using ((select public.is_catalog_admin())) with check ((select public.is_catalog_admin()))', t);
  end loop;
end $$;
create policy catalog_public_read on public.products for select to anon, authenticated using (activo);
create policy catalog_public_read on public.categories for select to anon, authenticated using (true);
create policy catalog_public_read on public.subcategories for select to anon, authenticated using (true);
-- Secuencias exactas (también cubre una tabla productos renombrada).
do $$ declare t text; seq text; maximum_id bigint; sequence_value bigint;
begin
  foreach t in array array['products','categories','subcategories'] loop
    seq := pg_get_serial_sequence('public.' || t, 'id');
    if seq is not null then
      execute format('grant usage on sequence %s to authenticated', seq);
      -- Las cargas históricas con IDs explícitos pueden haber dejado la secuencia atrás.
      execute format('select max(id) from public.%I', t) into maximum_id;
      execute format('select last_value from %s', seq) into sequence_value;
      if maximum_id >= sequence_value then perform setval(seq::regclass, maximum_id, true); end if;
    end if;
  end loop;
end $$;

