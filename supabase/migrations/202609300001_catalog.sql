-- Normalizar códigos; conservar el primer duplicado y asignar LEGACY-id al resto.
-- Evitar colisiones incluso si ya existe un código LEGACY-id.
do $$ declare r record; candidate text; suffix integer;
begin
  for r in select id, codigo from public.products order by id loop
    candidate := upper(btrim(coalesce(r.codigo, '')));
    if candidate !~ '^[A-Z0-9][A-Z0-9._/-]{0,63}$' or exists (
      select 1 from public.products where id < r.id and upper(btrim(codigo)) = candidate
    ) then
      candidate := 'LEGACY-' || r.id; suffix := 0;
      while exists (select 1 from public.products where id <> r.id and upper(btrim(codigo)) = candidate) loop
        suffix := suffix + 1; candidate := 'LEGACY-' || r.id || '-' || suffix;
      end loop;
    end if;
    update public.products set codigo = candidate where id = r.id and codigo is distinct from candidate;
  end loop;
end $$;
